def _fmt(v, col):
    if col in GENERAL:
        return "General"
    if col in PLAIN_INT or col.endswith("_n"):
        return "0"
    a = abs(v)
    if a == 0:
        return "0"
    for lo, f in NUM_FORMAT:
        if a >= lo:
            return f
    return "0.00E+00"


def _cell(v):
    if not isinstance(v, str) or v == "":
        return v
    try:
        return int(v) if v.lstrip("-").isdigit() else float(v)
    except ValueError:
        return v


def _put(ws, r, j, v):
    """Write a cell; a string beginning with `=` stays text (openpyxl would
    otherwise store it as a formula, which Excel rejects on opening)."""
    cell = ws.cell(r, j, v)
    if isinstance(v, str) and v.startswith("="):
        cell.data_type = "s"
    return cell



def tidy_panes(ws):
    """One selection per pane, each inside its pane, the active cell at the top left of
    the scrolling pane (Brad 2026-11-09). openpyxl leaves the active cell at A1 inside
    the frozen corner, and repeated freezes add duplicate selections; Excel then draws
    the frozen view wrongly until the sheet is scrolled."""
    from openpyxl.utils.cell import coordinate_from_string
    from openpyxl.worksheet.views import Selection
    sv = ws.sheet_view
    pane = sv.pane
    if pane is None or pane.state != "frozen":
        sv.selection = [Selection(activeCell="A1", sqref="A1")]
        return
    col, row = coordinate_from_string(pane.topLeftCell)
    sel = []
    if pane.xSplit and pane.ySplit:
        sel = [Selection(pane="topRight", activeCell=f"{col}1", sqref=f"{col}1"),
               Selection(pane="bottomLeft", activeCell=f"A{row}", sqref=f"A{row}"),
               Selection(pane="bottomRight", activeCell=pane.topLeftCell, sqref=pane.topLeftCell)]
        pane.activePane = "bottomRight"
    elif pane.ySplit:
        sel = [Selection(pane="bottomLeft", activeCell=f"A{row}", sqref=f"A{row}")]
        pane.activePane = "bottomLeft"
    else:
        sel = [Selection(pane="topRight", activeCell=f"{col}1", sqref=f"{col}1")]
        pane.activePane = "topRight"
    sv.selection = sel

def write_book(banded: dict, flat: dict, families: dict, notes: dict | None = None,
               flags: dict | None = None, grades: dict | None = None,
               grouped: set | None = None, band_notes: dict | None = None) -> str:
    """`grouped`: sheets whose _low, _high and _n columns are put in an Excel
    outline group beside their central column, folded when the book opens.
    `flags`: {sheet: {(archetype, column)}} -- cells whose value rests on a
    conversion factor from outside the source.
    `grades`: {sheet: {(archetype, column): grade}} -- cells the fill step wrote.
    On the graded sheets every value is shaded by how certain it is (SHADE); the
    key is on the readme sheet, the first sheet of the book."""
    warnings.filterwarnings("ignore")
    import openpyxl
    from openpyxl.comments import Comment
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    # Ember palette (Brad 2026-10-29): headers in its two darkest shades, the folded
    # _low/_high/_n headers in its middle shade, the certainty shading in muted tints
    # of it (SHADE), family bands in a neutral warm grey so they never read as shading
    HEAD, HEAD_D = PatternFill("solid", fgColor=EMBER[3]), PatternFill("solid", fgColor=EMBER[4])
    # header of the folded _low/_high/_n columns (modeller 2026-10-09)
    DET, DET_D = PatternFill("solid", fgColor=EMBER[2]), PatternFill("solid", fgColor="A33E00")
    BAND, WARN = PatternFill("solid", fgColor="EFEBE8"), PatternFill("solid", fgColor="F4F1EF")
    f_head, f_grp = Font(sz=12, bold=True, color="FFFFFF"), Font(sz=10, bold=True, color="FFFFFF", italic=True)
    f_unit, f_band = Font(sz=10, color=EMBER[0]), Font(sz=16, bold=True, color=EMBER[4])
    f_sub, f_body = Font(sz=11, bold=True, color=EMBER[3]), Font(sz=11)
    f_warn = Font(sz=11, bold=True, color=EMBER[4])
    f_note = Font(sz=10, italic=True, color=EMBER[4])
    rule = Border(bottom=Side(style="thin", color=EMBER[3]))
    SHADE_FILL = {k: PatternFill("solid", fgColor=c) for k, _, c, _, _ in SHADE if c}
    SHADE_FONT = {k: Font(sz=11, italic=k in ITALIC, color=fc) for k, _, _, fc, _ in SHADE if fc}

    def shade(cell, key):
        if key in SHADE_FILL:
            cell.fill = SHADE_FILL[key]
        if key in SHADE_FONT:
            cell.font = SHADE_FONT[key]

    wb = openpyxl.Workbook()
    wb.remove(wb.active)
    ws = wb.create_sheet("readme")
    ws.sheet_view.showGridLines = False
    ws.column_dimensions["A"].width = 2.5
    ws.column_dimensions["B"].width = 26
    ws.column_dimensions["C"].width = 173.57    # 1220 px (Brad 2026-10-29)
    r = 2
    for kind, text in README:
        if kind == "h":
            ws.cell(r, 2, text).font = Font(sz=18, bold=True, color=EMBER[4])
            r += 2
        elif kind == "h2":
            r += 1
            c = ws.cell(r, 2, text)
            c.font = Font(sz=13, bold=True, color="FFFFFF")
            for j in (2, 3):
                ws.cell(r, j).fill = HEAD
            r += 1
        elif kind == "p":
            c = ws.cell(r, 2, text)
            c.font, c.alignment = f_body, Alignment(wrap_text=True, vertical="top")
            ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=3)
            ws.row_dimensions[r].height = 15 * (1 + len(text) // 220)
            r += 1
        elif kind == "legend":
            for key, label, _, _, desc in SHADE:
                c = ws.cell(r, 2, label)
                c.font = f_body
                shade(c, key)
                ws.cell(r, 3, desc).font = f_body
                r += 1
            ws.cell(r, 2, "(none)").font = f_body
            ws.cell(r, 3, "Text, identifiers, and counts are not shaded.").font = f_body
            r += 1
        elif kind == "files":
            for name, text in CSV_NOTES:
                ws.cell(r, 2, name).font = Font(sz=11, bold=True)
                c = ws.cell(r, 3, text)
                c.font, c.alignment = f_body, Alignment(wrap_text=True, vertical="top")
                ws.row_dimensions[r].height = 15 * (1 + len(text) // 220)
                r += 1
        elif kind == "sheets":
            for name in list(banded) + list(flat):
                ws.cell(r, 2, name).font = Font(sz=11, bold=True)
                ws.cell(r, 3, SHEET_NOTES.get(name, "")).font = f_body
                r += 1
    for name, (cols, rows, groups, units, band, sub, banner) in banded.items():
        ws = wb.create_sheet(name)
        ws.sheet_view.showGridLines = False
        ws.column_dimensions["A"].width = 2.5
        first = 2
        ws.cell(1, 2, banner).font = f_warn
        for j in range(2, min(len(cols) + 2, 16)):
            ws.cell(1, j).fill = WARN
        ws.row_dimensions[1].height = 30
        for j, c in enumerate(cols, start=first):
            det = name in (grouped or ()) and c.endswith(DETAIL)
            for row_i, val, fill, font in ((3, groups.get(c, ""), DET_D if det else HEAD_D, f_grp),
                                           (4, c, DET if det else HEAD, f_head),
                                           (5, units.get(c, ""), DET if det else HEAD, f_unit)):
                cell = ws.cell(row_i, j, val)
                cell.fill, cell.font = fill, font
                cell.alignment = Alignment(horizontal="left", vertical="bottom", wrap_text=True)
                note = ((notes or {}).get(name) or {}).get(c) if row_i == 4 else None
                if note:
                    cell.comment = Comment(note, "technology database", width=320, height=160)
            ws.column_dimensions[get_column_letter(j)].width = (
                36 if j == first else 60 if c in ("full-citation", "applies-to", "description", "note")
                else max(10, min(20, len(c) + 3)))
        ws.row_dimensions[4].height = 46
        r, last_b, last_s = 7, None, None
        for row in rows:
            b, s = row.get(band, ""), row.get(sub, "") if sub else ""
            if b != last_b:
                r += 1
                ws.cell(r, first, families.get(b, b) or "(none)").font = f_band
                for j in range(first, len(cols) + first):
                    ws.cell(r, j).fill, ws.cell(r, j).border = BAND, rule
                if (band_notes or {}).get(b) and band in ("family", "_family"):
                    ws.cell(r, first + 1, band_notes[b]).font = f_note
                ws.row_dimensions[r].height = 22
                r += 1
                last_b, last_s = b, None
            if sub and s != last_s:
                ws.cell(r, first, f"*{s}").font = f_sub
                r += 1
                last_s = s
            for j, col in enumerate(cols, start=first):
                val = _cell(row.get(col, ""))
                cell = _put(ws, r, j, val)
                cell.font = f_body
                if name in (grades or {}):
                    key = grades[name].get((row.get("archetype"), col))
                    if key is None and (row.get("archetype"), col) in (flags or {}).get(name, ()):
                        key = "converted"
                    if (key is None and isinstance(val, (int, float)) and not isinstance(val, bool)
                            and groups.get(col, "identity") != "identity" and not col.endswith("_n")):
                        key = "sourced"
                    if key:
                        shade(cell, key)
                if j == first:
                    cell.alignment = Alignment(indent=1)
                elif isinstance(val, (int, float)) and not isinstance(val, bool):
                    cell.number_format = _fmt(val, col)
                    cell.alignment = Alignment(horizontal="left" if col in LEFT else "right")
                elif col in LEFT:
                    cell.alignment = Alignment(horizontal="left")
            r += 1
        ws.freeze_panes = ws.cell(6, first + 1).coordinate
        if name in (grouped or ()):
            # fold each parameter's _low/_high/_n run under its central column
            ws.sheet_properties.outlinePr.summaryRight = False
            run = []
            for j, c in enumerate(cols + [""], start=first):
                if c.endswith(DETAIL):
                    run.append(j)
                    continue
                if run:
                    ws.column_dimensions.group(get_column_letter(run[0]), get_column_letter(run[-1]),
                                               outline_level=1, hidden=True)
                    run = []
    for name, (cols, rows) in flat.items():
        ws = wb.create_sheet(name)
        ws.append(cols)
        for c in ws[1]:
            c.fill, c.font = HEAD, f_head
        for i, row in enumerate(rows, start=2):
            for j, c in enumerate(cols, start=1):
                _put(ws, i, j, _cell(row.get(c, "")))
        ws.freeze_panes = "B2"
        for j, c in enumerate(cols, start=1):
            ws.column_dimensions[get_column_letter(j)].width = max(10, min(40, len(c) + 4))
    for ws in wb.worksheets:
        ws.sheet_view.zoomScale = ZOOM
        ws.sheet_view.zoomScaleNormal = ZOOM
        tidy_panes(ws)
    try:
        wb.save(BOOK)
    except PermissionError:
        return "workbook is open in Excel; CSVs written, workbook not rebuilt"
    return f"{BOOK.name}: {len(wb.sheetnames)} sheets"
