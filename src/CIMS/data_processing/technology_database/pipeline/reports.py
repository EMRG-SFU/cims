"""Generated reports: the mapping review and the vocabulary document.

output/mapping-review.md is the one review of how source material reaches the
archetypes. It replaces the aggregation, design-crosswalk and CIMS reviews the
retired pipeline wrote. data/processed_data/technology_database/vocabulary.md is the readable form of the records.
Both are regenerated on every build; edit the records, never these.
"""
from __future__ import annotations

import re
from collections import Counter, defaultdict

from .common import OUTPUT, ROOT, VOCAB, read, split_list
from .hierarchy import Hierarchy

CAPTURE_WORDS = ("ccs", "capture", "post-combustion", "pre-combustion", "oxyfuel")
STOP = {"with", "and", "or", "the", "for", "on", "in", "to", "of", "a", "an", "by"}


def _words(text):
    return {w for w in re.split(r"[^a-z0-9]+", text.lower()) if len(w) > 2 and w not in STOP}


def _md(x):
    return str(x).replace("|", "/").replace("\n", " ")


def mapping_review(records, hier, loader, stamp, views, ex_result):
    arows = views["archetype"][1]
    status = Counter(a["core-sourced"] for a in arows)
    exs = loader.examples
    by_arch = defaultdict(list)
    for e in exs.values():
        by_arch[e.get("archetype", "")].append(e)
    nfacts = Counter(r["example-id"] for r in loader.facts + loader.flows + loader.cons)
    nexcl = Counter(r["example-id"] for r in loader.facts + loader.flows
                    if r.get("excluded") and r["excluded"] != "no number")
    L = []
    A = L.append
    A("# Mapping review\n")
    A("Generated by `src/technology_database/build.py`. How every example reaches an archetype, "
      "what could not be pooled and why, and what needs a decision. To change a mapping, "
      "edit the `archetype` cell of that example in `records/source-example.csv`.\n")
    A("## Summary\n")
    A(f"- **{len(arows)} archetypes**, by how many of the seven core model values come from a "
      "source: " + ", ".join(f"{status[n]} with {n}" for n in range(7, -1, -1) if status[n]) + ".")
    m = Counter(e["mapping"] for e in exs.values())
    A(f"- **{len(exs)} examples**: {m['mapped']} mapped, {m['none']} marked `(none)`, "
      f"{m['unmapped']} not yet mapped.")
    pooled = sum(1 for r in loader.facts if r.get("unit-norm") and not r.get("excluded"))
    A(f"- **{len(loader.facts)} parameter rows**: {pooled} pooled into the summaries; the "
      "rest are listed under *Not pooled* below.")
    A(f"- **Hierarchy snapshot**: {stamp['rows']} nodes, sha256 `{stamp['sha']}`. "
      + ("First build against this snapshot." if stamp["first-build"] else
         f"{len(stamp['added'])} nodes added and {len(stamp['removed'])} removed since the last build."))
    A("")
    if stamp["added"] or stamp["removed"]:
        A("## Hierarchy changes since the last build\n")
        for b in stamp["added"]:
            A(f"- added `{b}`")
        for b in stamp["removed"]:
            A(f"- removed `{b}`")
        A("")

    served = {r["node"] for r in views["application"]}
    in_scope = []
    for r in records.annotations:
        if r.get("note") == "not served by the database":
            continue
        for b in split_list(r["branches"]):
            for n in hier.expand(b):
                if n not in served and n not in [x for x, _ in in_scope]:
                    in_scope.append((n, r["annotation"]))
    A("## Hierarchy nodes no archetype serves\n")
    A("Nodes an annotation covers that no row of `records/archetype-service.csv` reaches.\n")
    if not in_scope:
        A("None.\n")
    for n, ann in in_scope:
        A(f"- `{Hierarchy.short(n)}` ({ann})")
    A("")

    un = [e for e in exs.values() if e["mapping"] == "unmapped"]
    A("## Examples not yet mapped\n")
    if not un:
        A("None.\n")
    else:
        A("| example | source | name | process |\n|---|---|---|---|")
        for e in sorted(un, key=lambda e: e["example-id"]):
            A(f"| `{e['example-id']}` | {records.short(e['source-id'])} | "
              f"`{e['source-technology']}` | {_md(e['process'])} |")
        A("")

    A("## Examples to check\n")
    A("Mappings seeded from the retired pipeline where the source's own name points "
      "somewhere else: its equipment differs from the archetype's, or it names capture "
      "and the archetype does not (or the reverse). Each may be right; each is a "
      "decision worth a look.\n")
    A("| archetype | example | why |\n|---|---|---|")
    assumed = {r["example-id"] for r in loader.facts if "device not named" in (r.get("note") or "")}
    k = 0
    for e in sorted(exs.values(), key=lambda e: (e.get("archetype", ""), e["example-id"])):
        a = records.by_key.get(e.get("archetype", ""))
        if not a:
            continue
        why = []
        eq = e["source-technology"].split("_")[0]
        if eq != a["equipment"]:
            why.append(f"equipment `{eq}`")
        cap_src = any(w in e["source-technology"] for w in CAPTURE_WORDS)
        cap_arch = ("ccs" in a["archetype"] or a["equipment"] == "capture-unit"
                    or "capture" in a["label"].lower() or "top-gas" in a["archetype"]
                    or "oxy-fuel" in a["archetype"])
        if cap_src != cap_arch:
            why.append("capture in one name only")
        if e["example-id"] in assumed:
            why.append("the source names no device; the device was assumed at extraction")
        if why:
            k += 1
            A(f"| `{a['archetype']}` | {records.short(e['source-id'])} `{e['source-technology']}` "
              f"({_md(e['process'])}) | {', '.join(why)} |")
    A(f"\n{k} examples.\n")

    A("## Not pooled\n")
    A("Rows converted to the archetype's basis are pooled; these were not.\n")
    reasons = Counter(r["excluded"] for r in loader.facts + loader.flows
                      if r.get("excluded") and r["excluded"] != "no number")
    A("| reason | rows |\n|---|---:|")
    for why, n in reasons.most_common():
        A(f"| {_md(why)} | {n} |")
    A("")

    aside, host = defaultdict(list), defaultdict(list)
    whole = [r for r in loader.facts if r.get("derived-kind") == "whole-plant"]
    for r in loader.facts:
        if r.get("set-aside") == "needs-efficiency":
            aside[r["archetype"]].append(r["record-id"])
        elif r.get("set-aside") == "needs-host-cost":
            host[r["archetype"]].append(r["record-id"])
    A("## Whole-plant costs for UKERC measures\n")
    A("A UKERC measure's cost is the cost of adding it to a plant. Where "
      "`records/reference/ukerc-host-baseline.csv` names the archetype's host step and UKERC "
      "states one baseline cost for it, the whole-plant cost (baseline + measure) is a derived "
      "row, and that row is what pools.\n")
    A("| row | archetype | formula | unit |\n|---|---|---|---|")
    for r in whole:
        A(f"| `{r['record-id']}` | `{r['archetype']}` | {r['formula']} | {r['unit']} |")
    A("")
    A("## Set aside: needs a host-plant cost\n")
    A("UKERC measure costs whose host has no baseline cost in the source, or whose archetype "
      "is not a host with measures added. Out of the summaries until a host cost is "
      "established; the worklist is `set-aside-host-cost.csv`.\n")
    for a_, ids in sorted(host.items()):
        A(f"- `{a_}`: {len(ids)} rows")
    A("")
    A("## Set aside: needs an efficiency factor\n")
    A("UKERC costs on energy-service archetypes. UKERC states them per tonne of the host "
      "plant's product, with the fuel used per tonne; its per-GJ figures are per GJ of "
      "fuel input. Per GJ of output needs the efficiency, which UKERC does not give, so "
      "they are out of the summaries until a factor is established. The worklist, with "
      "each example's fuel use per tonne, is `set-aside-efficiency.csv`.\n")
    if not aside:
        A("None.\n")
    for a_, ids in sorted(aside.items()):
        A(f"- `{a_}`: {len(ids)} rows")
    A("")

    A("## Service links with nothing to narrow them\n")
    A("An archetype placed on an end use made of several hierarchy nodes, where neither "
      "its route, its name nor its sources said which. It is linked to every node; "
      "remove the rows in `records/archetype-service.csv` that do not apply.\n")
    wide = defaultdict(list)
    for s in records.service:
        if "no evidence to narrow" in s.get("note", ""):
            wide[s["archetype"]].append(Hierarchy.short(s["branch"]))
    for a, bs in sorted(wide.items()):
        A(f"- `{a}`: {len(bs)} nodes ({', '.join(bs[:4])}{', ...' if len(bs) > 4 else ''})")
    A("")

    unrev = sum(1 for d in records.discriminators.values() if d.get("reviewed") != "yes")
    A("## Vocabulary\n")
    A(f"- {unrev} of {len(records.discriminators)} discriminators are not yet reviewed "
      "(`reviewed` column of `records/vocabulary/discriminator.csv`); their definition is "
      "seeded from the archetype labels that use them.")
    unused = [e for e, r in records.equipment.items()
              if not any(a["equipment"] == e for a in records.archetypes)]
    A(f"- {len(unused)} equipment terms no archetype uses: {', '.join(sorted(unused))}.")
    A("")

    A("## Examples by archetype\n")
    A("Every mapped example, grouped by family and archetype. `rows` counts its fact rows; "
      "`not pooled` those left out of the summaries.\n")
    fam_label = {f: r["label"] for f, r in records.families.items()}
    last = None
    for a in arows:
        es = by_arch.get(a["archetype"], [])
        if not es:
            continue
        if a["family"] != last:
            A(f"\n### {fam_label.get(a['family'], a['family'])}\n")
            A("| archetype | example | process | rows | not pooled |\n|---|---|---|---:|---:|")
            last = a["family"]
        for e in sorted(es, key=lambda e: (records.rank(e["source-id"]), e["example-id"])):
            A(f"| `{a['archetype']}` | {records.short(e['source-id'])} `{e['source-technology']}` | "
              f"{_md(e['process'])} | {nfacts[e['example-id']]} | {nexcl[e['example-id']] or ''} |")
    (OUTPUT / "mapping-review.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def vocabulary_md(records, hier, views):
    """data/processed_data/technology_database/vocabulary.md: the archetypes by family, the naming vocabularies and
    the hierarchy annotations, generated from the records."""
    arows = views["archetype"][1]
    L = []
    A = L.append
    A("# Vocabulary\n")
    A("Generated by `src/technology_database/build.py` from `data/technology_database/`. Do not edit; "
      "edit the records and rebuild. The naming rule and the tests for a new archetype "
      "are in [design.md](design.md).\n")
    A("## Families\n")
    A("| family | kind | label | archetypes |\n|---|---|---|---:|")
    n = Counter(a["family"] for a in arows)
    for f, r in records.families.items():
        A(f"| `{f}` | {r['kind']} | {_md(r['label'])} | {n[f]} |")
    A("")
    A("## Archetypes\n")
    A("Status: *quantified* (its examples' numbers are pooled), *not pooled* (its examples "
      "carry numbers none of which could be put on its basis), *named* (a source names it "
      "without numbers), *gap* (no example yet). `applies to` lists hierarchy nodes; `*` "
      "stands for one segment, usually the sector.\n")
    last = None
    for a in arows:
        if a["family"] != last:
            A(f"\n### {_md(records.families.get(a['family'], {}).get('label', a['family']))}\n")
            A("| archetype | label | type | carriers | TRL | applies to | core values sourced |")
            A("|---|---|---|---|---:|---|---|")
            last = a["family"]
        A(f"| `{a['archetype']}` | {_md(a['label'])} | {a['type']} | {_md(a['carriers'])} | "
          f"{a['trl']} | {_md(a['applies-to'])} | {a['core-sourced']} of 7 |")
    A("\n## Modifiers\n")
    A("| order | modifier | meaning |\n|---:|---|---|")
    for r in sorted(read(VOCAB / "modifier.csv"), key=lambda r: int(r["order"])):
        A(f"| {r['order']} | `{r['modifier']}` | {_md(r['definition'])} |")
    A("\n## Equipment\n")
    A("| equipment | definition | used by |\n|---|---|---:|")
    used = Counter(a["equipment"] for a in records.archetypes)
    for e, r in sorted(records.equipment.items()):
        A(f"| `{e}` | {_md(r.get('definition', ''))} | {used[e]} |")
    A("\n## Discriminators\n")
    A("| discriminator | definition | reviewed |\n|---|---|---|")
    for d, r in sorted(records.discriminators.items()):
        A(f"| `{d}` | {_md(r['definition'])} | {r.get('reviewed', '')} |")
    A("\n## Hierarchy annotations\n")
    A("What the database records about the hierarchy nodes it serves, grouped as the "
      "former design end uses were. `draws-on` names the annotation groups a node's "
      "process takes heat or drive from.\n")
    A("| annotation | nodes | service unit | heat demand | draws on |\n|---|---|---|---|---|")
    for r in records.annotations:
        nodes = "; ".join(Hierarchy.short(b) for b in split_list(r["branches"]))
        A(f"| `{r['annotation']}` {_md(r['label'])} | {_md(nodes)} | {_md(r['service-unit'])} | "
          f"{_md(r['heat-process-temp'])} | {_md(r['draws-on'])} |")
    (OUTPUT / "vocabulary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
