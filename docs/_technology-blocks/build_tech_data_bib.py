"""Build the bibliography of technology-database sources cited in the book.

The chapters cite sources from the technology database by their source id,
for example ``[@iea_2024_001]``. This script finds every such citation in
the book's .qmd files and writes ``tech-data_references.bib`` with an entry
for each, built from the database's verified citation details
(``records/reference/source-citation.csv``, falling back to
``output/source-list.csv``). Only cited sources are written, so the global
References page lists just those.

It can also list the sources behind an archetype, to help choose what to
cite:

    uv run python docs/_technology-blocks/build_tech_data_bib.py
    uv run python docs/_technology-blocks/build_tech_data_bib.py --sources blast-furnace

The database location defaults to ``../../../../tech_data`` relative to this
folder; set the environment variable ``CIMS_TECH_DATA`` to point elsewhere.
"""

from __future__ import annotations

import argparse
import csv
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOCS = HERE.parent
OUTPUT = DOCS / "tech-data_references.bib"
DEFAULT_TECH_DATA = HERE / ".." / ".." / ".." / ".." / "tech_data"


def read_csv(path: Path) -> list[dict]:
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def bib_escape(text: str) -> str:
    text = " ".join((text or "").split()).strip().rstrip(",")
    for ch in "&%#_$":
        text = text.replace(ch, "\\" + ch)
    return text


def authors(raw: str) -> str:
    """'Smith, A., Jones, B. and Lee, C.' -> 'Smith, A. and Jones, B. and Lee, C.'"""
    raw = " ".join((raw or "").split())
    if not raw:
        return ""
    parts = re.split(r",? and | & ", raw)
    people: list[str] = []
    for part in parts:
        # "Smith, A., Jones, B." -> pairs of surname, initials
        bits = [b.strip() for b in part.split(",") if b.strip()]
        if len(bits) >= 2 and all(re.fullmatch(r"([A-Z][a-z]?\.?-?\s?)+", b) for b in bits[1::2]):
            people += [f"{bits[i]}, {bits[i + 1]}" for i in range(0, len(bits) - 1, 2)]
        else:
            people.append(f"{{{part.strip()}}}")      # an organisation: keep it whole
    return " and ".join(people)


def entry(sid: str, cite: dict | None, listed: dict | None) -> str:
    cite, listed = cite or {}, listed or {}
    author = authors(cite.get("verified-authors", ""))
    title = cite.get("verified-title") or listed.get("full-citation") or sid
    year = cite.get("verified-year") or listed.get("year", "")
    fields = {
        "author": author or "{" + bib_escape(listed.get("short-name", sid).rsplit(" ", 1)[0]) + "}",
        "title": "{" + bib_escape(title) + "}",
        "year": bib_escape(year),
        "howpublished": bib_escape(cite.get("verified-publisher", "")),
        "doi": (cite.get("doi") or listed.get("doi") or "").strip(),
        "url": (cite.get("url") or listed.get("url") or "").strip(),
    }
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields.items() if v)
    return f"@misc{{{sid},\n{body}\n}}\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sources", metavar="ARCHETYPE", help="list the sources behind an archetype")
    args = ap.parse_args(argv)

    root = Path(os.environ.get("CIMS_TECH_DATA", DEFAULT_TECH_DATA)).resolve()
    listed = {r["source-id"]: r for r in read_csv(root / "database/harmonized/output/source-list.csv")}
    by_short = {r["short-name"]: r for r in listed.values()}
    citations = {r["source-id"]: r for r in
                 read_csv(root / "database/harmonized/records/reference/source-citation.csv")}

    if args.sources:
        arch = {r["archetype"]: r for r in read_csv(root / "database/harmonized/output/archetype.csv")}
        if args.sources not in arch:
            raise SystemExit(f"No archetype '{args.sources}'")
        for short in [s.strip() for s in arch[args.sources]["sources"].split(";") if s.strip()]:
            r = by_short.get(short)
            if r:
                print(f"{r['source-id']:32} {r['verification']:12} {short}: {r['full-citation'][:110]}")
            else:
                print(f"{'?':32} {'':12} {short}")
        return 0

    cited: set[str] = set()
    for qmd in DOCS.glob("*.qmd"):
        cited |= {k for k in re.findall(r"@([\w-]+)", qmd.read_text(encoding="utf-8")) if k in listed}
    text = ["% Generated by _technology-blocks/build_tech_data_bib.py from the technology",
            "% database's source list. Do not edit; rerun the script instead.", ""]
    text += [entry(sid, citations.get(sid), listed.get(sid)) for sid in sorted(cited)]
    OUTPUT.write_text("\n".join(text), encoding="utf-8")
    print(f"wrote {OUTPUT.name}: {len(cited)} sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
